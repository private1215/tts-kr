ROUNDTRIP = (4, 40, 44, 440000, 20, 35, 10, 10000, 500, 1000, 15)
pfails = 0
for t, exp in PARSE_CASES:
    got = _parse_sino_value(t)
    if got != exp and not (exp is None and got is None):
        pfails += 1
        print("❌ parse %-10s exp=%s got=%s" % (t, exp, got))
for n in ROUNDTRIP:
    s = _sino_int(n)
    if _parse_sino_value(s) != float(n):
        pfails += 1
        print("❌ roundtrip %d -> %r -> %s" % (n, s, _parse_sino_value(s)))

